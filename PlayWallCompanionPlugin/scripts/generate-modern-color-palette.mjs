#!/usr/bin/env node
// Regenerates src/domain/modernColorPalette.generated.ts from PlayWallClient's ModernColor.json —
// the actual runtime data the Java client loads (see ModernColor.java's static initializer). Run via
// "npm run sync-colors", or automatically as part of "npm run build"/"npm run dev".

import {readFileSync, writeFileSync} from 'node:fs'
import {dirname, relative, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const sourcePath = resolve(here, '../../PlayWallClient/src/main/resources/style/colors/ModernColor.json')
const outputPath = resolve(here, '../src/domain/modernColorPalette.generated.ts')

const entries = JSON.parse(readFileSync(sourcePath, 'utf8'))

const paletteLines = entries
    .map((entry) => `    ${entry.name}: {bg: '${entry.colors.hi}', font: '${entry.colors.font}'},`)
    .join('\n')

const content = `// AUTO-GENERATED by scripts/generate-modern-color-palette.mjs — do not edit by hand.
// Source of truth: PlayWallClient/src/main/resources/style/colors/ModernColor.json. Regenerate with
// "npm run sync-colors" (also runs automatically as part of "npm run build"/"npm run dev").

export interface ModernColorEntry {
    /** Background color, PlayWallClient's "hi" shade. */
    bg: string
    /** Black or white — whichever PlayWall picked as readable against \`bg\`. */
    font: string
}

export const MODERN_COLOR_PALETTE: Record<string, ModernColorEntry> = {
${paletteLines}
}
`

writeFileSync(outputPath, content)
console.log(`Wrote ${entries.length} colors to ${relative(process.cwd(), outputPath)}`)
